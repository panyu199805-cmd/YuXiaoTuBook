EBOOK_BODY = """生活里绝大多数矛盾，都源于不会说话。
伴侣争吵、亲子对立、职场人际内耗、朋友渐行渐远……很多时候我们并没有恶意，只是随口的指责、下意识的评判、习惯性的推卸，把关心说成了指责，把委屈说成了愤怒，把诉求变成了对抗。
马歇尔·卢森堡在《非暴力沟通》中告诉我们：大部分语言暴力，都不是大声争吵，而是藏在评判、比较、命令和道德绑架里；伤人的从来不是事实，是我们说话的思维方式。
这本书推翻了我们传统的沟通逻辑，它不教话术、不教圆滑处世、不教博弈说服，只教我们一件事：剥离情绪和偏见，看见自己，也看见别人，用温和清晰的方式，建立人与人之间真诚的联结。
很多人误以为非暴力沟通就是低声下气、迁就忍让，其实恰恰相反。它的核心本质：不委屈自己，不伤害别人，清晰表达诉求，共情接纳他人。
全书最核心的精髓，就是简单却极具力量的沟通四步法：观察、感受、需要、请求。

第一步：区分观察与评判，只说事实，不贴标签。
我们日常90%的矛盾，都混淆了事实和主观评价。我们习惯说“你总是不上心、你太懒惰、你从来不尊重我”，这类带着偏见的定论，就是语言暴力的开端。没有人喜欢被否定、被贴标签，一旦听到评判，人的第一反应不是反思，而是防御和反驳。
成熟的沟通，是放下“总是、从不、每次”这类绝对化词汇，客观陈述发生的事情。不说“你总是迟到不在乎我”，只说“这周三次见面，你都迟到了半小时以上”。不带偏见的客观观察，是好好说话的第一步。

第二步：表达真实感受，不指责归咎。
我们最常犯的错误，是把情绪甩给别人：“你让我很生气、你害得我很烦”。这种表达方式，把自己情绪的责任推给对方，矛盾自然升级。
非暴力沟通强调：我的情绪，从来不是别人的行为造成的。别人的行为只是导火索，真正决定我们心情的，是我们内心未被满足的需求。我们只需要坦诚说出自我感受，而非指责对方：不说“你让我很生气”，换成“你迟到的时候，我会感到不安和失落”。

第三步：挖掘感受背后，底层的内在需求。
这是全书最核心、最治愈的底层逻辑：所有负面情绪，本质都是自身需求没有被满足。
我们愤怒、委屈、难过、焦虑，根源不是对方做错了事，是我们内心的尊重、陪伴、安全感、理解、被认可、边界感等核心需求没有被满足。迟到带来的不安，本质是渴望被重视；别人忽视我们的想法，本质是渴望被尊重；工作疲惫内耗，本质是渴望休息和被理解。
看懂这一点，你就会停止内耗：情绪向内归因，我们才不会被别人牵着鼻子走。

第四步：提出具体请求，分清请求和命令。
很多沟通失败，都输在诉求模糊、语气强硬。我们习惯下达命令：“你不许迟到、你必须多陪我、你要改掉坏习惯”。带有胁迫和道德绑架的是命令，对方顺从是迫于压力，拒绝就会引发冲突；而温和、具体、给对方选择权的，才是请求。
把四步串联起来，就是所有人都能直接套用的万能沟通句式：当我看到（客观事实），我感到（我的感受），因为我需要（底层需求），能不能请你（具体可执行的请求）。

除了向外表达，这本书更教会我们向内倾听和共情。
沟通从来不是单方面说服别人，分为向外表达、向内倾听两大能力。
多数人倾听的时候，都在踩坑：急于讲道理、给建议、安慰劝解、评判对错。但真正的共情倾听，不需要说教，不需要开导，只需要放下自己的偏见和立场，听懂对方情绪背后的需求。别人倾诉难过的时候，不必急着说“这点小事没什么大不了”，只需要看见他的委屈，读懂他的诉求。
更重要的是，我们要学会和自己对话，完成自我共情。
很多人对内格外苛刻：习惯性自我否定、陷入焦虑内疚、苛责自己不够优秀。对待自己，我们同样要用非暴力沟通：客观接纳自己的不完美，正视自己的负面情绪，理解自己的疲惫，放过不完美的自己。学会温柔对待自己，才有能力温柔对待别人。
书中还点明了四种我们每天都在使用的暴力沟通模式，也是所有人际矛盾的根源：道德评判贴标签、拿他人互相比较、遇事推卸回避责任、强人所难道德绑架。这些无意识的说话习惯，慢慢消耗掉亲情、爱情和友情。
包括我们难以控制的愤怒，书中也给出了答案：愤怒从来不是别人的错，是我们对事情的偏见和评判催生了怒火。化解愤怒最好的方式，不是压抑脾气，也不是发泄情绪，而是停止指责，找到愤怒背后没被满足的需求。
读完《非暴力沟通》才明白：所谓好好说话，不是圆滑讨好，不是收敛脾气迎合别人；
是不被情绪裹挟，不言语伤人；既能守住自己的边界，坦然表达诉求；也能包容他人的不同，理解别人的难处。
语言是有温度的，温柔且有力量的沟通，能化解世间大半的人际烦恼。管好语言，放下偏见，好好沟通，就是成年人最高级的自律。"""

